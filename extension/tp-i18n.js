var TP_LANG = 'ko';

function tpPickLang(stored, uiLang) {
  if (stored && TP_SUPPORTED_LANGS.includes(stored)) return stored;
  const base = String(uiLang || '').slice(0, 2).toLowerCase();
  return TP_SUPPORTED_LANGS.includes(base) ? base : 'en';
}
function tpSetLang(lang) {
  TP_LANG = TP_SUPPORTED_LANGS.includes(lang) ? lang : 'en';
}
// T('st_loaded', { n: 3 }) → 플레이스홀더 치환. 번역 누락 시 한국어 → 그래도 없으면 키 그대로.
function T(key, vars) {
  const d = TP_LOCALES[TP_LANG] || {};
  let s = d[key] != null ? d[key] : TP_LOCALES.ko[key];
  if (typeof s !== 'string') s = String(key);
  if (vars) {
    for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  }
  return s;
}
