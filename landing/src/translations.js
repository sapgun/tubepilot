export const languages = [
  { code: "ko", name: "한국어", short: "KO" },
  { code: "en", name: "English", short: "EN" },
  { code: "ja", name: "日本語", short: "JA" },
  { code: "pt", name: "Português", short: "PT" },
  { code: "es", name: "Español", short: "ES" },
];
const indexes = { en: 0, ja: 1, pt: 2, es: 3 };
export function initialLocale() {
  const url = new URL(location.href).searchParams.get("lang");
  if (languages.some((l) => l.code === url)) return url;
  try {
    const saved = localStorage.getItem("tubepilot-locale");
    if (languages.some((l) => l.code === saved)) return saved;
  } catch {}
  return "ko";
}
let locale = typeof window === "undefined" ? "ko" : initialLocale();
export function getLocale() {
  return locale;
}
export function setLocale(value) {
  if (!languages.some((l) => l.code === value)) return;
  locale = value;
  try {
    localStorage.setItem("tubepilot-locale", value);
  } catch {}
  const url = new URL(location.href);
  url.searchParams.set("lang", value);
  history.replaceState(null, "", url);
}
export function t(key, vars = {}) {
  let result =
    locale === "ko" ? key : (messages[key]?.[indexes[locale]] ?? key);
  for (const [k, v] of Object.entries(vars))
    result = result.replaceAll(`{${k}}`, String(v));
  return result;
}
